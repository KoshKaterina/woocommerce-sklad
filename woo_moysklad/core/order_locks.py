# Замок по номеру заказа: один заказ обрабатывается строго одним потоком.
#
# Зачем. У интеграции два входа, и оба умеют создать заказ в МС: вебхук источника
# и сверка по таймеру. Проверка «такой заказ уже есть?» только СПРАШИВАЕТ МойСклад,
# номер за собой не занимая, поэтому при одновременной работе обоих входов оба
# получали «нет» и создавали свой заказ. 27.08.2026 так родилась пара 06784/06785
# по заказу сайта 18643 — пятый случай с 10.08 (разбор и хронология по секундам:
# knowledge/woo-sklad-dubli-zakazov.md в рабочей папке).
#
# Процесс в контейнере один (uvicorn запускается без --workers), поэтому хватает
# внутрипроцессного threading-замка: вебхук работает в потоке asyncio.to_thread,
# сверка — в потоке threading.Timer.

import threading
from contextlib import contextmanager

_mutex = threading.Lock()
_busy: set[str] = set()


@contextmanager
def claim_order(order_number: str):
    """Занять номер заказа на время обработки.

    Отдаёт True, если номер был свободен и теперь занят нами. Отдаёт False, если
    этот же заказ прямо сейчас обрабатывает другой поток — тогда обработку надо
    пропустить: тот, кто держит номер, доведёт её до конца. Если он упадёт с
    ошибкой, заказ подберёт следующая сверка (она ходит раз в 3 минуты).

    Пропуск, а не ожидание — сознательно: ждать чужую обработку означает держать
    поток минуты (создание контрагента, поиск товаров, запросы в МС), а выигрыша
    нет — дождавшийся всё равно увидит уже созданный заказ и выйдет.
    """
    with _mutex:
        acquired = order_number not in _busy
        if acquired:
            _busy.add(order_number)
    try:
        yield acquired
    finally:
        if acquired:
            with _mutex:
                _busy.discard(order_number)


def busy_orders() -> set[str]:
    """Снимок занятых номеров — для диагностики и тестов."""
    with _mutex:
        return set(_busy)
